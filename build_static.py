"""Build the free, dependency-free web version for a Hugging Face Static Space.

Why not Gradio-Lite: it installs Python packages in the browser at load time,
and an upstream dependency change broke it. This build has no external
dependencies at all: one self-contained index.html that loads instantly.

Single source of truth: the vocabulary and regex patterns are exported from
ncr_assistant/ into the page as JSON; web/engine.js mirrors only the scoring
logic, and tests/test_web_parity.py checks it against Python row by row.

Usage:
    python build_static.py        # writes space/index.html and space/README.md
"""

from __future__ import annotations

import csv
import html
import json
from pathlib import Path

from ncr_assistant import classifier, rules

ROOT = Path(__file__).parent
OUT = ROOT / "space"


def engine_config() -> dict:
    """Everything the JS engine needs, taken straight from the Python modules."""
    return {
        "vague_terms": list(rules.VAGUE_TERMS),
        "cause_patterns": list(rules.CAUSE_PATTERNS),
        "condition_terms": list(rules.CONDITION_TERMS),
        "location_terms": list(rules.LOCATION_TERMS),
        "location_patterns": list(rules.LOCATION_PATTERNS),
        "measurement_pattern": rules.MEASUREMENT_PATTERN.pattern,
        "min_words": rules.MIN_WORDS,
        "max_words": rules.MAX_WORDS,
        "categories": {k: list(v) for k, v in classifier.CATEGORIES.items()},
    }


def load_examples(n: int = 8) -> list[str]:
    with (ROOT / "data" / "synthetic_ncr_descriptions.csv").open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    good = [r["description"] for r in rows if r["quality"] == "good"]
    poor = [r["description"] for r in rows if r["quality"] == "poor"]
    return [t for pair in zip(poor, good) for t in pair][:n]


